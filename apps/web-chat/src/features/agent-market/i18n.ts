export const amDictionaries = { th, en } as const;

export type AmT = (key: AmKey, vars?: Record<string, string>) => string;

function lookup(locale: string, key: AmKey, vars?: Record<string, string>): string {
  const dict: Record<AmKey, string> = locale === "th" ? th : en;
  const raw = dict[key] ?? th[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => (vars[name] !== undefined ? vars[name] : `{${name}}`));
}

/** The feature's lookup for the active app locale. Name the result `t`. */
export function useAmT(): AmT {
  const locale = useI18nStore((s) => s.locale);
  return (key, vars) => lookup(locale, key, vars);
}

/** Non-hook lookup (API errors, toasts) — reads the locale at call time. */
export function tAm(key: AmKey, vars?: Record<string, string>): string {
  return lookup(useI18nStore.getState().locale, key, vars);
}

/** The active locale (for date formatting). */
export function useAmLocale(): string {
  return useI18nStore((s) => s.locale);
}

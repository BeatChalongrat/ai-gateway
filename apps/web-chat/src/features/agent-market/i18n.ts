export type AmT = (key: AmKey, vars?: Record<string, string>) => string;

/** A key the language has no word for reads in Thai (the first language), then as the key. */
function lookup(locale: Locale, key: AmKey, vars?: Record<string, string>): string {
  const dict: Partial<Record<AmKey, string>> = amDictionaries[locale] ?? th;
  const raw = dict[key] ?? th[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => (vars[name] !== undefined ? vars[name] : `{${name}}`));
}

// One lookup per language, made once: the function a component holds changes
// only when the language does, so an effect that lists `t` re-runs then and
// at no other time.
const LOOKUPS: Record<Locale, AmT> = {
  th: (key, vars) => lookup("th", key, vars),
  en: (key, vars) => lookup("en", key, vars),
};

/** The feature's lookup, in the language this part of the screen reads in
 *  (the app's, or its LocaleScope's). Name the result `t`. */
export function useAmT(): AmT {
  return LOOKUPS[useLocale()] ?? LOOKUPS.th;
}

/** Non-hook lookup (API errors, toasts): the app's language at the moment of the call. */
export function tAm(key: AmKey, vars?: Record<string, string>): string {
  return lookup(useI18nStore.getState().locale, key, vars);
}

/** The language this part of the screen reads in — for dates (format.ts). */
export function useAmLocale(): Locale {
  return useLocale();
}

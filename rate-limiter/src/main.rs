//! Rate-limiter gRPC sidecar entry point.
//!
//! Wires up:
//!   1. ``deadpool-redis`` pool from ``REDIS_URL``
//!   2. ``SlidingWindow`` engine over that pool
//!   3. tonic gRPC server on ``GRPC_PORT`` (default 50053)
//!   4. plain HTTP metrics + ``/healthz`` on ``METRICS_PORT`` (default 9101)
//!
//! All four pieces share one Tokio runtime — the metrics server
//! runs as a spawned task so the gRPC ``Serve`` future stays the
//! foreground job and a SIGTERM cleanly stops both.

use std::convert::Infallible;
use std::env;
use std::net::SocketAddr;

use deadpool_redis::Runtime;
use hyper::service::{make_service_fn, service_fn};
use hyper::{Body, Method, Request, Response, Server, StatusCode};
use tonic::transport::Server as TonicServer;
use tracing::{error, info};

mod metrics;
mod server;
mod sliding_window;

// Generated by ``build.rs`` via tonic-build.
pub mod pb {
    tonic::include_proto!("ratelimit");
}

fn env_or(key: &str, fallback: &str) -> String {
    env::var(key).unwrap_or_else(|_| fallback.into())
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "rate_limiter=info,tonic=info".into()),
        )
        .init();

    metrics::init();

    let redis_url = env_or("REDIS_URL", "redis://redis:6379");
    let grpc_port: u16 = env_or("GRPC_PORT", "50053").parse()?;
    let metrics_port: u16 = env_or("METRICS_PORT", "9101").parse()?;

    info!(
        redis_url = %redis_url,
        grpc_port,
        metrics_port,
        "rate-limiter booting"
    );

    let pool = deadpool_redis::Config::from_url(&redis_url)
        .create_pool(Some(Runtime::Tokio1))
        .map_err(|e| {
            error!(error = ?e, "failed to build redis pool");
            e
        })?;

    let engine = sliding_window::SlidingWindow::new(pool);
    let svc = server::RateLimitServer::new(engine);

    // ---- HTTP metrics + healthz ----
    tokio::spawn(async move {
        let addr: SocketAddr = ([0, 0, 0, 0], metrics_port).into();
        let make_svc = make_service_fn(|_| async {
            Ok::<_, Infallible>(service_fn(http_handler))
        });
        let server = Server::bind(&addr).serve(make_svc);
        info!(%addr, "metrics+healthz listening");
        if let Err(e) = server.await {
            error!(error = ?e, "metrics server error");
        }
    });

    // ---- gRPC ----
    let grpc_addr: SocketAddr = ([0, 0, 0, 0], grpc_port).into();
    info!(%grpc_addr, "gRPC listening");
    TonicServer::builder()
        .add_service(pb::rate_limit_service_server::RateLimitServiceServer::new(svc))
        .serve_with_shutdown(grpc_addr, async {
            tokio::signal::ctrl_c().await.ok();
            info!("shutdown signal received");
        })
        .await?;

    info!("shutdown complete");
    Ok(())
}

async fn http_handler(req: Request<Body>) -> Result<Response<Body>, Infallible> {
    match (req.method(), req.uri().path()) {
        (&Method::GET, "/healthz") => Ok(Response::builder()
            .status(StatusCode::OK)
            .header("content-type", "text/plain")
            .body(Body::from("ok\n"))
            .unwrap()),
        (&Method::GET, "/metrics") => {
            let body = metrics::render();
            Ok(Response::builder()
                .status(StatusCode::OK)
                .header("content-type", "text/plain; version=0.0.4")
                .body(Body::from(body))
                .unwrap())
        }
        _ => Ok(Response::builder()
            .status(StatusCode::NOT_FOUND)
            .body(Body::from("not found\n"))
            .unwrap()),
    }
}

"""FIX40 — generate the over-masking corpus (``overmask_d.json`` / ``overmask_e.json``).

EVERYTHING HERE IS SYNTHETIC. No real person, company, number or address.

Why a new file and not more rows in ``messages_{a,b,c}.json``: those 72
messages and ``criteria.json`` are the locked FIX37 instrument. Adding to
them would move every historical number. These live under a different
filename so ``harness.load_messages()`` (which globs ``messages_*.json``)
keeps returning exactly 72, and the new set is scored beside it.

What the set is for — the two blind spots FIX38 could not see:

1. **Two Thai words separated by a space that are NOT a name.** Every decoy
   in the old set is a single word (``แก้วน้ำ``, ``ข้าวโอ๊ต``), so nothing
   ever exercised ``thai_name_no_prefix`` Pass 1, whose whole shape is
   "two space-separated Thai tokens + a context keyword nearby".
2. **Questions whose answer depends on the words NEXT TO a masked span.**
   The old axis-A questions survive masking by construction, so
   ``comprehension_retention`` read 1.00 while ``12 ใบ แตก 3 ใบ`` was being
   turned into ``12 <<PERSON_B>> 3 ใบ``. The ``adjacent`` question kind
   below is the one that breaks when masking eats into the sentence.

Shapes covered (FIX40 §2.1), tagged per message in ``shapes``:
  s1 number + classifier + verb      s5 nickname-as-object
  s2 two ordinary words              s6 business term split by a space
  s3 word that can also be a name    s7 a real name that MUST still mask
  s4 same word as name and as noun

Run:  python -m evals.mask_quality.data.gen_overmask
"""


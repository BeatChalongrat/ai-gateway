# ── helpers ───────────────────────────────────────────────────────────────


def msg(
    mid: str,
    scenario: str,
    shapes: list[str],
    text: str,
    *,
    pii: list[dict] | None = None,
    keep: list[str] | None = None,
    q: list[dict] | None = None,
) -> dict:
    return {
        "id": mid,
        "scenario": scenario,
        "shapes": shapes,
        "text": text,
        "pii": pii or [],
        "must_not_mask": keep or [],
        "questions": q or [],
    }


def adj(qid: str, question: str, expect: list[list[str]]) -> dict:
    """A question whose answer dies if masking eats the words around a span."""
    return {"id": qid, "kind": "adjacent", "q": question, "expect_any": expect}


def ctx(qid: str, question: str, expect: list[list[str]]) -> dict:
    return {"id": qid, "kind": "context", "q": question, "expect_any": expect}


def ident(qid: str, question: str, leak: list[str]) -> dict:
    return {"id": qid, "kind": "identity", "q": question, "leak_values": leak}



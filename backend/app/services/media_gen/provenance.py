"""Provenance metadata for generated media (Sprint 5).

Provider-disclosed transparency info — C2PA manifests, SynthID/visible
watermarks, generation seed/params — attached to a finished job under
``generation_jobs.output_metadata.provenance``. Used for compliance,
downstream watermark detection, and the end-user "AI-generated by …" badge.

Reconciliation note (Sprint 5 Phase 0): the original plan injected this
*inside* the adapters, which the Hard Rules forbid ("Do NOT modify any
adapter"). Instead the job loop calls :func:`build_provenance` after a job
reaches ``done`` — adapters stay sealed. The loop already has everything
needed: ``job.provider``, ``job.model_id``, and the adapter's
``result_metadata`` (seed / completed_at / metrics, when the provider
returns them).

The defaults below are CONSERVATIVE and reflect documented provider
behaviour at the time of writing — they are NOT a live probe. An adapter
may override any field by putting its own ``provenance`` dict in
``result_metadata``; :func:`build_provenance` gives that precedence.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Optional


@dataclass
class ProvenanceMetadata:
    """Provider-disclosed provenance info attached to generated media.

    Stored in ``generation_jobs.output_metadata.provenance``.
    """

    provider: str                              # "replicate" | "openai" | "elevenlabs"
    model_id: str                              # provider's model path / id
    c2pa_embedded: Optional[bool] = None       # provider embeds a C2PA manifest
    synthid_embedded: Optional[bool] = None    # SynthID watermark present
    visible_watermark: Optional[bool] = None   # visible overlay present
    generation_seed: Optional[int] = None      # seed, if the provider returned one
    generation_params: Optional[dict] = None   # sanitized echo of input params
    provider_disclosed_at: Optional[str] = None  # ISO timestamp from the provider

    def to_dict(self) -> dict:
        """Serialise, dropping ``None`` fields (keeps the JSONB compact)."""
        return {k: v for k, v in asdict(self).items() if v is not None}


# What we KNOW each provider does by default. Conservative where a provider's
# behaviour is per-model (we under-claim rather than over-claim a watermark).
PROVIDER_PROVENANCE_DEFAULTS: dict[str, dict] = {
    "replicate": {
        # Replicate is a model host; C2PA/watermarking is per-model and not
        # embedded by the platform. Conservative defaults.
        "c2pa_embedded": False,
        "synthid_embedded": False,
        "visible_watermark": False,
    },
    "openai": {
        # OpenAI embeds C2PA on image/video output; TTS audio carries no
        # visible watermark.
        "c2pa_embedded": True,
        "synthid_embedded": False,
        "visible_watermark": False,
    },
    "elevenlabs": {
        # ElevenLabs participates in the C2PA/CAI coalition per public docs.
        "c2pa_embedded": True,
        "synthid_embedded": False,
        "visible_watermark": False,
    },
}


def build_provenance(
    provider: str,
    model_id: str,
    result_metadata: Optional[dict] = None,
) -> dict:
    """Build the provenance dict for a finished job.

    Pure function — no I/O, no adapter coupling. The job loop calls this with
    the job's provider/model and the adapter's ``result_metadata``.

    Precedence:
      1. An explicit ``provenance`` dict in ``result_metadata`` (an adapter
         that already discloses) wins field-by-field.
      2. Otherwise the conservative :data:`PROVIDER_PROVENANCE_DEFAULTS`.
      3. ``seed`` / ``completed_at`` are lifted from ``result_metadata`` when
         the provider returned them.
    """
    meta = result_metadata or {}
    defaults = PROVIDER_PROVENANCE_DEFAULTS.get(provider, {})

    seed = meta.get("generation_seed", meta.get("seed"))
    prov = ProvenanceMetadata(
        provider=provider,
        model_id=model_id,
        generation_seed=int(seed) if isinstance(seed, (int, str)) and str(seed).lstrip("-").isdigit() else None,
        provider_disclosed_at=meta.get("provider_disclosed_at") or meta.get("completed_at"),
        **defaults,
    )
    base = prov.to_dict()

    # Adapter-supplied provenance overrides field-by-field (future-proofing;
    # no current adapter does this, but the contract is honoured).
    supplied = meta.get("provenance")
    if isinstance(supplied, dict):
        base.update({k: v for k, v in supplied.items() if v is not None})
    return base

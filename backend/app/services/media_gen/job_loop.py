"""Lifespan job loop for async media generation (Sprint 2A).

Polls ``generation_jobs`` for queued work, claims one under Postgres
advisory lock ``900004`` (worker.py owns 900001-900003) with ``FOR UPDATE
SKIP LOCKED``, then drives it to completion via the registered provider
adapter:

    submit_job → poll until done/failed → fetch bytes → store + mark done.

The CLAIM is Postgres-only (advisory lock + SKIP LOCKED); on any other
dialect the loop idles. The PROCESS step is ORM-based and dialect-agnostic
so it can be unit/integration-tested on SQLite by calling ``_process_job``
directly.

Generated bytes are written to the backend output dir
(``MEDIA_GEN_OUTPUT_DIR``, default ``/tmp/media_gen_outputs``) and served
by the internal jobs route; chat-edge fetches them and persists the
ConversationFile on its side (cross-DB), so ``output_file_id`` stays NULL
here and the status route derives ``output_url`` from ``output_metadata``.

Cancellation-safe: the lifespan cancels the task on shutdown, mirroring the
daily loops in ``main.py``.
"""

from __future__ import annotations

import asyncio
import json
import logging
import os
import time
from datetime import datetime, timezone

from sqlalchemy import text

from app.observability.metrics import (
    GEN_COST_CREDITS,
    GEN_DURATION_SECONDS,
    GEN_FAILURE_TOTAL,
    GEN_JOBS_ACTIVE,
)
from app.services.media_gen.registry import UnknownProviderError, get_adapter

log = logging.getLogger(__name__)

# Advisory-lock id for the generation job claim (worker.py uses
# 900001/900002/900003 — see backend/worker.py:42-44).
LOCK_GENERATION_JOBS = 900004

_MAX_PER_CYCLE = 50


def _poll_interval() -> float:
    try:
        return max(1.0, float(os.getenv("GENERATION_JOB_POLL_INTERVAL", "5")))
    except (TypeError, ValueError):
        return 5.0


def _adapter_poll_interval() -> float:
    # Webhook-aware default (Sprint 2B): when a Replicate webhook is
    # configured it's the primary completion signal, so poll less
    # aggressively; otherwise poll faster. An explicit env override still
    # wins (tests set it low).
    from app.core.config import settings

    if (settings.replicate_webhook_secret or "").strip():
        default = settings.replicate_poll_interval_sec_with_webhook
    else:
        default = settings.replicate_poll_interval_sec_no_webhook
    try:
        return max(
            0.2,
            float(os.getenv("GENERATION_JOB_ADAPTER_POLL_SECONDS", str(default))),
        )
    except (TypeError, ValueError):
        return float(default)


def _max_job_seconds() -> float:
    try:
        return max(5.0, float(os.getenv("GENERATION_JOB_MAX_SECONDS", "600")))
    except (TypeError, ValueError):
        return 600.0


def _output_dir() -> str:
    d = os.getenv("MEDIA_GEN_OUTPUT_DIR", os.path.join(os.path.sep, "tmp", "media_gen_outputs"))
    os.makedirs(d, exist_ok=True)
    return d


def _is_postgres(session) -> bool:
    try:
        return session.bind.dialect.name == "postgresql"
    except Exception:  # noqa: BLE001 — best-effort dialect probe
        return False


async def _claim_one(session) -> str | None:
    """Claim one queued job under the advisory lock; mark it processing.

    Returns the claimed job id, or None when nothing is available / the
    advisory lock is held elsewhere. Postgres-only.
    """
    got = (
        await session.execute(
            text("SELECT pg_try_advisory_lock(:id)"),
            {"id": LOCK_GENERATION_JOBS},
        )
    ).scalar()
    if not got:
        return None
    try:
        row = (
            await session.execute(
                text(
                    "SELECT id FROM generation_jobs WHERE status = 'queued' "
                    "ORDER BY created_at LIMIT 1 FOR UPDATE SKIP LOCKED"
                )
            )
        ).first()
        if row is None:
            return None
        job_id = row[0]
        await session.execute(
            text(
                "UPDATE generation_jobs "
                "SET status = 'processing', started_at = now() WHERE id = :id"
            ),
            {"id": job_id},
        )
        await session.commit()
        return job_id
    finally:
        await session.execute(
            text("SELECT pg_advisory_unlock(:id)"),
            {"id": LOCK_GENERATION_JOBS},
        )
        await session.commit()


def _coerce_meta(meta) -> dict:
    if isinstance(meta, dict):
        return meta
    if isinstance(meta, str):
        try:
            parsed = json.loads(meta)
            return parsed if isinstance(parsed, dict) else {}
        except Exception:  # noqa: BLE001
            return {}
    return {}


async def _process_job(session, job_id: str) -> None:
    """Drive a single claimed job to a terminal state via its adapter.

    ORM-based so it runs on SQLite (tests) and Postgres alike. Never
    raises: any failure marks the job failed.
    """
    from app.models.generation_job import GenerationJobORM

    job = await session.get(GenerationJobORM, job_id)
    if job is None:
        return
    provider = job.provider
    modality = job.job_type

    try:
        adapter = get_adapter(provider, job.job_type)
    except UnknownProviderError as exc:
        job.status = "failed"
        job.error_code = "no_adapter"
        job.error_message = str(exc)[:500]
        job.completed_at = datetime.now(timezone.utc)
        await session.commit()
        GEN_FAILURE_TOTAL.labels(modality, provider, "no_adapter").inc()
        log.info("generation job %s failed: no_adapter", job_id)
        return

    meta = _coerce_meta(job.input_metadata)
    GEN_JOBS_ACTIVE.labels(modality).inc()
    t0 = time.monotonic()
    try:
        submit = await adapter.submit_job(job.input_prompt, meta)
        job.external_job_id = submit.external_job_id
        await session.commit()

        result_url = None
        result_meta: dict = {}
        if submit.sync_result is not None:
            result_url = submit.sync_result.result_url
            result_meta = submit.sync_result.result_metadata or {}
        else:
            deadline = time.monotonic() + _max_job_seconds()
            interval = _adapter_poll_interval()
            while True:
                # Webhook awareness (Sprint 2B): a Replicate webhook may have
                # finalized this job out-of-band. Re-read; if terminal, stop
                # polling — poll is the fallback, the webhook is primary.
                await session.refresh(job)
                if job.status in ("done", "failed", "cancelled"):
                    return
                poll = await adapter.poll_job(submit.external_job_id)
                if poll.progress_pct is not None and poll.progress_pct != job.progress_pct:
                    job.progress_pct = int(poll.progress_pct)
                    await session.commit()
                if poll.status == "done":
                    result_url = poll.result_url
                    result_meta = poll.result_metadata or {}
                    break
                if poll.status == "failed":
                    job.status = "failed"
                    job.error_code = (poll.error_code or "provider_failed")[:64]
                    job.error_message = poll.error_message or "provider reported failure"
                    job.completed_at = datetime.now(timezone.utc)
                    await session.commit()
                    GEN_FAILURE_TOTAL.labels(
                        modality, provider, job.error_code
                    ).inc()
                    return
                if time.monotonic() > deadline:
                    job.status = "failed"
                    job.error_code = "timeout"
                    job.error_message = "generation timed out"
                    job.completed_at = datetime.now(timezone.utc)
                    await session.commit()
                    GEN_FAILURE_TOTAL.labels(modality, provider, "timeout").inc()
                    return
                await asyncio.sleep(interval)

        data = await adapter.fetch_result_bytes(result_url)
        out_path = os.path.join(_output_dir(), f"{job_id}.mp4")
        with open(out_path, "wb") as fh:
            fh.write(data)

        actual = int(job.estimated_cost_credits)
        job.status = "done"
        job.progress_pct = 100
        # Provenance (Sprint 5): built here, not in the adapter (adapters are
        # sealed). Pure function over provider/model + the adapter's
        # result_metadata (seed / completed_at, when disclosed).
        from app.services.media_gen.provenance import build_provenance

        job.output_metadata = {
            "output_path": out_path,
            "content_type": (result_meta or {}).get("content_type", "video/mp4"),
            "size": len(data),
            "provenance": build_provenance(provider, job.model_id, result_meta),
        }
        job.actual_cost_credits = actual
        job.completed_at = datetime.now(timezone.utc)
        await session.commit()

        GEN_DURATION_SECONDS.labels(modality, provider, "done").observe(
            time.monotonic() - t0
        )
        GEN_COST_CREDITS.labels(modality, provider).observe(actual)
        log.info(
            "generation job %s done provider=%s size=%dB", job_id, provider, len(data)
        )
    except Exception as exc:  # noqa: BLE001 — never let one job kill the loop
        log.exception("generation job %s processing failed", job_id)
        try:
            await session.rollback()
            job = await session.get(GenerationJobORM, job_id)
            if job is not None and job.status not in ("done", "failed"):
                job.status = "failed"
                job.error_code = "processing_error"
                job.error_message = str(exc)[:500]
                job.completed_at = datetime.now(timezone.utc)
                await session.commit()
            GEN_FAILURE_TOTAL.labels(modality, provider, "processing_error").inc()
        except Exception:  # noqa: BLE001
            pass
    finally:
        GEN_JOBS_ACTIVE.labels(modality).dec()


async def run_generation_job_loop() -> None:
    """Background lifespan loop. Cancelled on app shutdown."""
    interval = _poll_interval()
    log.info(
        "generation job loop starting (interval=%ss, advisory_lock=%s)",
        interval,
        LOCK_GENERATION_JOBS,
    )
    from app.core.db import get_async_session_factory

    while True:
        try:
            factory = get_async_session_factory()
            async with factory() as session:
                if _is_postgres(session):
                    for _ in range(_MAX_PER_CYCLE):
                        job_id = await _claim_one(session)
                        if job_id is None:
                            break
                        await _process_job(session, job_id)
                else:
                    log.debug("generation job loop idle: non-postgres dialect")
        except asyncio.CancelledError:
            log.info("generation job loop cancelled")
            raise
        except Exception:  # noqa: BLE001 — a failed cycle must not kill the loop
            log.exception("generation job loop cycle failed")

        await asyncio.sleep(interval)

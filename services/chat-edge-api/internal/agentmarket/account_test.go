// seedAgentData gives an install one run with a step blob, an upload, an
// artifact and an index row — objects in storage and rows in every table.
func (e *testEnv) seedAgentData(in Install) (Run, []string) {
	e.t.Helper()
	ctx := context.Background()
	put := func(key, body string) {
		if err := e.api.files.Upload(ctx, key, strings.NewReader(body), "", int64(len(body))); err != nil {
			e.t.Fatal(err)
		}
	}
	run, _, err := e.store.CreateRun(ctx, e.store.Pool, Run{InstallID: in.ID, TenantID: in.TenantID, UserID: in.UserID, Kind: KindRun,
		Message: "[AM2] export test", DefinitionVersion: in.DefinitionVersion, Checksum: in.Checksum}, "")
	if err != nil {
		e.t.Fatal(err)
	}
	fid := uuid.New()
	upload := UploadKey(in.TenantID, in.ID, fid, "invoice.pdf")
	put(upload, "%PDF-1.4 the upload")
	rid := run.ID
	if _, err := e.store.CreateFile(ctx, e.store.Pool, File{ID: fid, TenantID: in.TenantID, UserID: in.UserID, InstallID: in.ID,
		RunID: &rid, Name: "invoice.pdf", Size: 19, SHA256: "aa", StorageKey: upload, Status: "active"}); err != nil {
		e.t.Fatal(err)
	}
	blob := BlobKey(in.TenantID, run.ID, strings.Repeat("ab", 16), "parsed.json")
	put(blob, `{"parsed":true}`)
	st, _, err := e.store.BeginStep(ctx, run.ID, "parse:invoice.pdf", "ingest", "k1", json.RawMessage(`{}`))
	if err != nil {
		e.t.Fatal(err)
	}
	out, _ := json.Marshal(map[string]any{"ref": map[string]any{"key": blob}})
	if err := e.store.FinishStep(ctx, st.ID, "succeeded", out, "", "", "", 1); err != nil {
		e.t.Fatal(err)
	}
	art := ArtifactKey(in.TenantID, run.ID, "register_v1.xlsx")
	put(art, "PK the register")
	if _, _, err := e.store.InsertArtifact(ctx, Artifact{RunID: run.ID, InstallID: in.ID, Format: "xlsx", Kind: "table",
		Name: "register_v1.xlsx", Version: 1, StorageKey: art, Size: 15, SHA256: "bb", ProducedByStep: "k2"}, in.TenantID, in.UserID); err != nil {
		e.t.Fatal(err)
	}
	if _, err := e.store.AddDocumentIndex(ctx, run, []IndexEntry{{DocKey: "d1", Name: "invoice.pdf", SHA256: "aa"}}, time.Hour); err != nil {
		e.t.Fatal(err)
	}
	return run, []string{upload, blob, art}
}

func TestAccountProviderExportsStopsAndPurges(t *testing.T) {
	e := newEnv(t)
	if e == nil {
		return
	}
	ctx := context.Background()
	mine := e.install()
	run, keys := e.seedAgentData(mine)
	// another user's install in the same tenant stays untouched
	other := e.user
	other.UserID = uuid.New()
	e.user, other = other, e.user
	theirs := e.install()
	e.user = other
	_, theirKeys := e.seedAgentData(theirs)

	p := NewAccountProvider(e.store, e.api.files) // without the background sweep of AccountProvider()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	lines, err := p.Export(ctx, mine.TenantID, mine.UserID, func(path string, r io.Reader) error {
		w, err := zw.Create(p.Name() + "/" + path)
		if err == nil {
			_, err = io.Copy(w, r)
		}
		return err
	})
	if err != nil || len(lines) == 0 {
		t.Fatalf("export: %v %v", lines, err)
	}
	_ = zw.Close()
	zr, _ := zip.NewReader(bytes.NewReader(buf.Bytes()), int64(buf.Len()))
	got := map[string]string{}
	for _, f := range zr.File {
		rc, _ := f.Open()
		b, _ := io.ReadAll(rc)
		rc.Close()
		got[f.Name] = string(b)
	}
	for _, doc := range []string{"installs.json", "settings.json", "runs.json", "steps.json", "clarifications.json", "approvals.json",
		"exceptions.json", "files.json", "artifacts.json", "thread.json", "budgets.json", "document_index.json"} {
		if _, ok := got["agent-market/"+doc]; !ok {
			t.Fatalf("export has no %s", doc)
		}
	}
	if !strings.Contains(got["agent-market/installs.json"], mine.ID.String()) || strings.Contains(got["agent-market/installs.json"], theirs.ID.String()) {
		t.Fatal("the export holds the user's installs and nobody else's")
	}
	var bytesOK, outOK bool
	for name, body := range got {
		bytesOK = bytesOK || (strings.HasPrefix(name, "agent-market/files/") && body == "%PDF-1.4 the upload")
		outOK = outOK || (strings.HasPrefix(name, "agent-market/outputs/") && body == "PK the register")
	}
	if !bytesOK || !outOK {
		t.Fatalf("the uploaded and generated bytes are in the export: %v", func() []string {
			var n []string
			for k := range got {
				n = append(n, k)
			}
			return n
		}())
	}

	if n, err := p.Stop(ctx, mine.UserID); err != nil || n["runs_stopped"] != 1 {
		t.Fatalf("stop: %v %v", n, err)
	}
	if r, _ := e.store.RunByID(ctx, run.ID); r.Status != RunCancelled {
		t.Fatalf("a queued run is cancelled at the deletion request: %s", r.Status)
	}

	counts, err := p.Purge(ctx, mine.UserID)
	if err != nil {
		t.Fatal(err)
	}
	// AM4: the seeded round was cancelled at the request, so nothing of the
	// organisation's is left in the install: it is erased whole (the
	// duplicate index goes with it)
	if counts["objects"] != 3 || counts["installs"] != 1 || counts["org_records_kept"] != 0 {
		t.Fatalf("purge counts: %v", counts)
	}
	for _, k := range keys {
		if ok, _ := e.api.files.Exists(ctx, k); ok {
			t.Fatalf("object left: %s", k)
		}
	}
	for _, q := range []string{`SELECT count(*) FROM agent_market.agent_installs WHERE user_id = $1`,
		`SELECT count(*) FROM agent_market.agent_runs WHERE user_id = $1`,
		`SELECT count(*) FROM agent_market.agent_files WHERE user_id = $1`,
		`SELECT count(*) FROM agent_market.agent_output_artifacts WHERE user_id = $1`,
		`SELECT count(*) FROM agent_market.document_index WHERE user_id = $1`} {
		var n int
		_ = e.store.Pool.QueryRow(ctx, q, mine.UserID).Scan(&n)
		if n != 0 {
			t.Fatalf("%s: %d left", q, n)
		}
	}
	for _, k := range theirKeys {
		if ok, _ := e.api.files.Exists(ctx, k); !ok {
			t.Fatalf("another user's object was deleted: %s", k)
		}
	}
	if again, err := p.Purge(ctx, mine.UserID); err != nil || again["installs"] != 0 {
		t.Fatalf("a second purge finds nothing: %v %v", again, err)
	}
}

func TestSweepActsOnlyOnDeletionsTheCoreRecorded(t *testing.T) {
	e := newEnv(t)
	if e == nil {
		return
	}
	ctx := context.Background()
	var audit bool
	_ = e.store.Pool.QueryRow(ctx, `SELECT to_regclass('chat.deletion_audit') IS NOT NULL`).Scan(&audit)
	if !audit {
		t.Skip("no chat.deletion_audit in this database")
	}
	gone := e.install()
	e.seedAgentData(gone)
	other := e.user
	e.user.UserID = uuid.New()
	kept := e.install()
	_, keptKeys := e.seedAgentData(kept)
	e.user = other
	p := NewAccountProvider(e.store, e.api.files)
	// nobody recorded as deleted: nothing happens, whoever is or is not in identity.users
	if n, err := p.SweepDeletedUsers(ctx); err != nil || n != 0 {
		t.Fatalf("sweep with no deletion recorded: %d %v", n, err)
	}
	if _, err := e.store.Pool.Exec(ctx, `INSERT INTO chat.deletion_audit (tenant_id, user_id, actor, action, scope, resource_id, rule)
		VALUES ($1, $2, 'system:account-purge', 'account_purged', 'user', $2, 'user_request')`, gone.TenantID, gone.UserID); err != nil {
		t.Fatal(err)
	}
	if n, err := p.SweepDeletedUsers(ctx); err != nil || n != 1 {
		t.Fatalf("sweep: %d %v", n, err)
	}
	var left, other2 int
	_ = e.store.Pool.QueryRow(ctx, `SELECT count(*) FROM agent_market.agent_installs WHERE user_id = $1`, gone.UserID).Scan(&left)
	_ = e.store.Pool.QueryRow(ctx, `SELECT count(*) FROM agent_market.agent_installs WHERE user_id = $1`, kept.UserID).Scan(&other2)
	if left != 0 || other2 != 1 {
		t.Fatalf("purged user left %d installs; the other has %d", left, other2)
	}
	for _, k := range keptKeys {
		if ok, _ := e.api.files.Exists(ctx, k); !ok {
			t.Fatalf("the other user's object was deleted: %s", k)
		}
	}
	_, _ = e.store.Pool.Exec(ctx, `DELETE FROM chat.deletion_audit WHERE user_id = $1`, gone.UserID)
}
